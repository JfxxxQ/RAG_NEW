"""
    指代改写：结合历史对话，把用户的指代词替换成具体事件/人物/时间
"""

from RAG_app.common.LoadModel import LoadModel

def re_question(question, history_list):
    model = LoadModel().local_llm
    prompt = f"""
            你是一个查询改写助手，任务是把用户问题中的指代词替换成具体内容，让问题可以独立检索。

            # 什么是"指代词"
            这件事、那件事、他、她、它、那个人、那次比赛、这个、那个、后来、结果如何、还有呢
            
            # 改写规则
            1. 结合【历史对话记录】，找出指代词指代的具体人、事、时间、地点。
            2. 把指代词替换成具体内容，输出一个完整、独立的问题。
            3. 如果当前问题没有指代词，原样输出。
            4. 如果历史记录为空，原样输出。
            5. 如果无法确定指代内容，原样输出，不要编造。
            6. 当用户提出这个新闻怎么样的时候，指代词改写为聊天信息最近的新闻的那一条
            
            # 输出要求
            - 只输出改写后的问题，不要输出任何解释、标点、前缀、引号。
            - 不要输出"改写后："这样的前缀。
            - 不要换行，只输出一行文本。
            - 不要输出"为："这样的前缀
            - 输出内容不能有任何前缀，只需要问题本身
            
            # 示例
            
            ## 示例1：有指代，能确定
            历史对话：
            用户：2014年洲际国奥男篮争霸赛发生了什么
            助手：2014年洲际国奥男篮争霸赛于7月5日至7日在云南曲靖举行，共有四支国奥男篮参赛。
            当前问题：这件事的冠军是谁
            输出：2014年洲际国奥男篮争霸赛的冠军是谁
            
            ## 示例2：有人名指代
            历史对话：
            用户：杨宪益先生是谁
            助手：杨宪益是中国著名翻译家，被誉为译界泰斗。
            当前问题：他是什么时候去世的
            输出：杨宪益先生是什么时候去世的
            
            ## 示例3：追问"后来"
            历史对话：
            用户：2014年巴西世界杯决赛结果如何
            助手：德国1比0战胜阿根廷夺冠。
            当前问题：后来呢
            输出：2014年巴西世界杯决赛后发生了什么
            
            ## 示例4：无指代，原样输出
            历史对话：
            用户：2014年洲际国奥男篮争霸赛发生了什么
            助手：2014年洲际国奥男篮争霸赛于7月5日至7日在云南曲靖举行。
            当前问题：2014年世界杯决赛结果如何
            输出：2014年世界杯决赛结果如何
            
            ## 示例5：历史为空，原样输出
            历史对话：（空）
            当前问题：这件事的冠军是谁
            输出：这件事的冠军是谁
            
            # 现在开始
            
            历史对话：
            {history_list}
            
            当前问题：{question}
            
            输出：
    """


    # 指代改写
    rs = model.invoke(prompt).content
    return rs

